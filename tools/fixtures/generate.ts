// CLI: node tools/fixtures/generate.ts [--check] [--only name]
// Writes fixtures/out/*.mp4 and fixtures/manifest.json. With --check, regenerates
// everything and fails unless every byte matches the committed manifest.
import { createHash } from 'node:crypto';
import * as fs from 'node:fs';
import * as path from 'node:path';
import { fileURLToPath } from 'node:url';
import type { Mp4Sink } from '../../src/media/mp4/muxer.ts';
import { buildFixture, corrupt, FIXTURES, type FixtureInfo, type FixtureSpec } from './build.ts';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../..');
export const OUT_DIR = path.join(ROOT, 'fixtures/out');
export const MANIFEST = path.join(ROOT, 'fixtures/manifest.json');

export interface ManifestEntry extends Partial<FixtureInfo> {
  file: string;
  bytes: number;
  sha256: string;
  spec?: FixtureSpec;
}
export type Manifest = Record<string, ManifestEntry>;

/** Streams to a file while hashing; patches are applied on disk and the hash is recomputed at the end. */
class FileSink implements Mp4Sink {
  private fd: number;
  private pos = 0;
  private pending: Uint8Array[] = [];
  private pendingBytes = 0;
  readonly file: string;
  constructor(file: string) {
    this.file = file;
    this.fd = fs.openSync(file, 'w');
  }
  private flush(): void {
    if (this.pendingBytes === 0) return;
    fs.writeSync(this.fd, Buffer.concat(this.pending));
    this.pending = [];
    this.pendingBytes = 0;
  }
  write(data: Uint8Array): void {
    this.pending.push(data);
    this.pos += data.length;
    this.pendingBytes += data.length;
    if (this.pendingBytes > 1 << 22) this.flush();
  }
  patch(position: number, data: Uint8Array): void {
    this.flush();
    fs.writeSync(this.fd, data, 0, data.length, position);
  }
  close(): number {
    this.flush();
    fs.closeSync(this.fd);
    return this.pos;
  }
}

export function sha256File(file: string): string {
  const h = createHash('sha256');
  const fd = fs.openSync(file, 'r');
  const buf = Buffer.alloc(1 << 22);
  for (;;) {
    const n = fs.readSync(fd, buf, 0, buf.length, null);
    if (n === 0) break;
    h.update(buf.subarray(0, n));
  }
  fs.closeSync(fd);
  return h.digest('hex');
}

function generateOne(spec: FixtureSpec, dir: string): ManifestEntry {
  const file = path.join(dir, spec.name + '.mp4');
  const sink = new FileSink(file);
  const info = buildFixture(spec, sink);
  const bytes = sink.close();
  return { file: spec.name + '.mp4', bytes, sha256: sha256File(file), spec, ...info };
}

export function generateAll(dir: string, only?: string): Manifest {
  fs.mkdirSync(dir, { recursive: true });
  const manifest: Manifest = {};
  for (const spec of FIXTURES) {
    if (only && spec.name !== only) continue;
    manifest[spec.name] = generateOne(spec, dir);
  }
  if (!only || only === 'corrupt') {
    const src = path.join(dir, 'clip_24.mp4');
    if (!fs.existsSync(src)) generateOne(FIXTURES[0] as FixtureSpec, dir);
    const bad = corrupt(new Uint8Array(fs.readFileSync(src)));
    const file = path.join(dir, 'corrupt.mp4');
    fs.writeFileSync(file, bad);
    manifest.corrupt = { file: 'corrupt.mp4', bytes: bad.length, sha256: sha256File(file) };
  }
  return manifest;
}

export function readManifest(): Manifest {
  return JSON.parse(fs.readFileSync(MANIFEST, 'utf8')) as Manifest;
}

/** Generate any fixture missing from fixtures/out (size check only). Used by test setup. */
export function ensureFixtures(): void {
  const manifest = readManifest();
  for (const [name, entry] of Object.entries(manifest)) {
    const file = path.join(OUT_DIR, entry.file);
    if (fs.existsSync(file) && fs.statSync(file).size === entry.bytes) continue;
    generateAll(OUT_DIR, name);
  }
}

function main(argv: string[]): void {
  const check = argv.includes('--check');
  const onlyAt = argv.indexOf('--only');
  const only = onlyAt >= 0 ? argv[onlyAt + 1] : undefined;
  const t0 = Date.now();
  const manifest = generateAll(OUT_DIR, only);
  const secs = ((Date.now() - t0) / 1000).toFixed(1);
  if (check) {
    const stored = readManifest();
    const bad = Object.keys(manifest).filter((k) => stored[k]?.sha256 !== manifest[k]?.sha256);
    if (bad.length) {
      console.error(`Fixtures differ from manifest: ${bad.join(', ')}`);
      process.exit(1);
    }
    console.log(`fixtures: ${Object.keys(manifest).length} regenerated byte-identical in ${secs}s`);
    return;
  }
  if (!only) fs.writeFileSync(MANIFEST, JSON.stringify(manifest, null, 1) + '\n');
  console.log(`fixtures: ${Object.keys(manifest).length} written in ${secs}s`);
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) main(process.argv.slice(2));
